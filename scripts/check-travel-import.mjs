import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
import '../dist/travel-template.js';
import '../dist/travel-importer.js';
const T=globalThis.PPTravelTemplate,I=globalThis.PPTravelImporter;
const initial={version:1,profile:{name:'Traveler'},trips:[{id:'existing-trip',name:'Europe Exchange 2027',start:'2027-01-13',end:'',notes:'My own notes',status:'draft'},{id:'family-trip',name:'End-of-Exchange Family Trip',start:'',end:'',notes:'Family note'}],destinations:[{id:'paris',tripId:'existing-trip',name:'Paris',country:'France',status:'wishlist',arrival:'',departure:'',lat:48.8566,lng:2.3522,notes:'My Paris note'}],activities:[],tasks:[],packing:[],expenses:[{id:'expense',amount:42}],bookings:[{id:'booking',reference:'keep-me'}],skiTrips:[],journal:[],dismissed:[]};
const first=I.analyze(initial);
assert.equal(initial.destinations.length,1);
assert.equal(first.state.trips.length,2);
assert.equal(first.state.destinations.find(d=>d.id==='paris').notes,'My Paris note');
assert.equal(first.state.bookings[0].reference,'keep-me');
assert.equal(first.state.expenses[0].amount,42);
assert.equal(first.state.packing.length,T.packing.length);
assert(first.state.packing.every(p=>p.ownership==='unknown'&&p.packedQty===0&&p.purchaseNeededQty===null));
assert(T.packing.every(p=>p.icon&&(existsSync(new URL(`../dist/assets/icons/${p.icon}.svg`,import.meta.url))||p.icon==='suitcase')));
assert(first.state.transfers.some(t=>t.origin==='Paris'&&t.destination==='Rome'&&t.mode==='flight'&&t.status==='planned'));
assert(first.state.activities.some(a=>a.title.includes('King of Triglav')&&a.date==='2027-05-30'));
assert(first.state.destinations.some(d=>d.name==='Hallstatt'&&d.tripId==='family-trip'));
const second=I.analyze(first.state);
for(const key of ['trips','destinations','activities','tasks','packing','transfers'])assert.equal(second.state[key].length,first.state[key].length,key);
const packingOnly=I.analyze({...initial,trips:[],destinations:[],packing:[]},{itinerary:false,packing:true});
assert.equal(packingOnly.state.trips.length,1);
assert.equal(packingOnly.state.destinations.length,0);
assert.equal(packingOnly.state.packing.length,T.packing.length);
const conflict=I.analyze({...initial,destinations:[{...initial.destinations[0],arrival:'2027-01-20'}]});
assert(conflict.conflicts.some(c=>c.name==='Paris'&&c.field==='arrival'));
assert.equal(conflict.state.destinations.find(d=>d.id==='paris').arrival,'2027-01-20');
console.log(`Travel import passed: ${first.state.destinations.length} destinations, ${first.state.activities.length} activities, ${first.state.transfers.length} transport legs, ${first.state.packing.length} packing items; repeat import idempotent.`);
